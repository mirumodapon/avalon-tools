import type { Plugin } from 'vite'

/** Served next to sw.js and pulled in with importScripts. */
export const CLEANUP_SCRIPT = 'sw-cleanup.js'

/**
 * Service worker code that deletes precaches left at exactly this worker's scope by
 * anyone else — older builds and the 1.x worker (`workbox-precache-v2-<origin>/`).
 *
 * Workbox's own `cleanupOutdatedCaches` matches any cache whose name merely *contains*
 * the scope, so home (scope `/`) would also delete `/record/`'s cache. Matching the
 * name's end keeps nested apps' caches safe.
 */
export function cleanupScript(cacheId: string): string {
  return `// Generated by @avalon/pwa: remove precaches of older workers at this exact scope.
self.addEventListener('activate', function (event) {
  var own = ${JSON.stringify(`${cacheId}-precache-`)}
  event.waitUntil(
    caches.keys().then(function (names) {
      var scope = self.registration.scope
      return Promise.all(
        names
          .filter(function (n) {
            return n.indexOf('-precache-') !== -1 && n.slice(-scope.length - 1) === '-' + scope && n.indexOf(own) !== 0
          })
          .map(function (n) {
            return caches.delete(n)
          }),
      )
    }),
  )
})
`
}

/** Emits {@link CLEANUP_SCRIPT} into the build for the worker to import. */
export function swCleanupPlugin(cacheId: string): Plugin {
  return {
    name: 'avalon-sw-cleanup',
    apply: 'build',
    generateBundle() {
      this.emitFile({ type: 'asset', fileName: CLEANUP_SCRIPT, source: cleanupScript(cacheId) })
    },
  }
}
