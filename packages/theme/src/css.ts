import { contrastRatio, ensureContrast } from './contrast.ts'
import { ACCENT_NAMES, COLOR_NAMES, FLAVOR_NAMES, hexOf, isDarkFlavor } from './palette.ts'

/** Minimum contrast for the `-fg` (text-safe) variant of each color against `base`. */
export const TEXT_CONTRAST = 4.5

/**
 * Generates the CSS custom properties for every flavor and accent, derived from
 * `@catppuccin/palette`. Each color gets a raw `--ctp-<name>` and a text-safe
 * `--ctp-<name>-fg` that is adjusted (mixed toward `text`) to reach WCAG AA on `base`.
 */
export function generateThemeCss(): string {
  const lines: string[] = [
    '/* Generated by @avalon/theme (scripts/generate.ts) from @catppuccin/palette. Do not edit. */',
  ]
  for (const flavor of FLAVOR_NAMES) {
    const base = hexOf(flavor, 'base')
    const text = hexOf(flavor, 'text')
    lines.push(`[data-flavor='${flavor}'] {`)
    lines.push(`  color-scheme: ${isDarkFlavor(flavor) ? 'dark' : 'light'};`)
    for (const color of COLOR_NAMES) {
      const hex = hexOf(flavor, color)
      lines.push(`  --ctp-${color}: ${hex};`)
      lines.push(`  --ctp-${color}-fg: ${ensureContrast(hex, base, text, TEXT_CONTRAST)};`)
    }
    lines.push('}')
    for (const accent of ACCENT_NAMES) {
      const hex = hexOf(flavor, accent)
      const onAccent = contrastRatio(base, hex) >= contrastRatio(text, hex) ? base : text
      // Same element, or nested (e.g. accent/flavor preview swatches inside <html>).
      lines.push(
        `[data-flavor='${flavor}'][data-accent='${accent}'], [data-flavor='${flavor}'] [data-accent='${accent}'], [data-accent='${accent}'] [data-flavor='${flavor}'] {`,
      )
      lines.push(`  --ctp-accent: var(--ctp-${accent});`)
      lines.push(`  --ctp-accent-fg: var(--ctp-${accent}-fg);`)
      lines.push(`  --ctp-on-accent: ${onAccent};`)
      lines.push('}')
    }
  }
  return `${lines.join('\n')}\n`
}
